use crate::codegen::TableMap;
use crate::driver::query_gen::generate_query_fn;
use crate::driver::traits::{Driver, path_alias, uses_module, uses_name};
use crate::driver::type_map::TypeContext;
use crate::options::TypeOverride;
use crate::plugin::plugin::Query;
use crate::utils::CodeWriter;

/// Generate a Gleam query module for a group of queries from the same SQL file.
///
/// The body is generated first; imports are then derived from what the body
/// actually uses, so the module never has unused or missing imports.
pub fn generate_queries(
    queries: &[&Query],
    table_map: &TableMap,
    overrides: &[TypeOverride],
    ctx: &TypeContext,
    models_import: Option<&str>,
    driver: &dyn Driver,
) -> Result<String, String> {
    let mut body = CodeWriter::new();
    for (i, query) in queries.iter().enumerate() {
        if i > 0 {
            body.blank();
        }
        generate_query_fn(query, table_map, overrides, ctx, &mut body, driver)?;
    }
    let body = body.into_string();

    let mut helpers = CodeWriter::new();
    driver.write_helpers(&body, ctx, &mut helpers);
    let helpers = helpers.into_string();
    let all = format!("{body}\n{helpers}");

    let mut w = CodeWriter::new();
    w.line("// Code generated by sqlc-gen-gleam. DO NOT EDIT.");
    w.blank();
    for line in import_lines(&all, models_import, driver) {
        w.line(&line);
    }
    w.blank();
    let mut out = w.into_string();
    out.push_str(&body);
    if !helpers.is_empty() {
        out.push('\n');
        out.push_str(&helpers);
    }
    Ok(out)
}

fn import_lines(code: &str, models_import: Option<&str>, driver: &dyn Driver) -> Vec<String> {
    let mut lines = Vec::new();
    for module in ["float", "int", "list"] {
        if uses_module(code, module) {
            lines.push(format!("import gleam/{module}"));
        }
    }
    let option_items: Vec<&str> = [
        ("Option", "type Option"),
        ("None", "None"),
        ("Some", "Some"),
    ]
    .into_iter()
    .filter(|(name, _)| uses_name(code, name))
    .map(|(_, item)| item)
    .collect();
    if !option_items.is_empty() {
        lines.push(format!(
            "import gleam/option.{{{}}}",
            option_items.join(", ")
        ));
    } else if uses_module(code, "option") {
        lines.push("import gleam/option".to_string());
    }
    for module in ["result", "string"] {
        if uses_module(code, module) {
            lines.push(format!("import gleam/{module}"));
        }
    }

    let mut external = vec![
        driver.import_path().to_string(),
        driver.decode_import_path().to_string(),
    ];
    external.extend(driver.extra_imports(code));
    if let Some(models) = models_import {
        external.push(models.to_string());
    }
    external.sort();
    external.dedup();
    for path in external {
        if uses_module(code, &path_alias(&path)) {
            lines.push(format!("import {path}"));
        }
    }
    lines
}
